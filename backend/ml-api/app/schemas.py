from pydantic import BaseModel, Field, field_validator
from typing import Optional, Literal, Dict, Any, Union

class PredictionRequest(BaseModel):
    Age: int = Field(..., ge=18, le=100, description="Employee age (18 to 100)")
    Department: str = Field(..., description="Department name")
    MonthlyIncome: float = Field(..., gt=0, description="Monthly income in currency units")
    JobLevel: int = Field(..., ge=1, le=5, description="Job level (1 to 5)")
    JobSatisfaction: int = Field(..., ge=1, le=4, description="Job satisfaction rating (1 to 4)")
    OverTime: str = Field(..., description="OverTime status ('Yes' or 'No')")
    YearsAtCompany: int = Field(..., ge=0, le=60, description="Total years at company")
    WorkLifeBalance: int = Field(..., ge=1, le=4, description="Work life balance rating (1 to 4)")
    DistanceFromHome: int = Field(..., ge=0, le=200, description="Distance from home in km/miles")

    @field_validator("OverTime")
    @classmethod
    def validate_overtime(cls, v: str) -> str:
        cleaned = str(v).strip().capitalize()
        if cleaned in ["Yes", "Y", "True", "1"]:
            return "Yes"
        elif cleaned in ["No", "N", "False", "0"]:
            return "No"
        raise ValueError("OverTime must be 'Yes' or 'No'")

    @field_validator("Department")
    @classmethod
    def validate_department(cls, v: str) -> str:
        valid_departments = [
            "Finance",
            "Sales",
            "IT",
            "Human Resources",
            "Research & Development"
        ]
        cleaned = str(v).strip()
        # Case insensitive match if possible
        for dept in valid_departments:
            if dept.lower() == cleaned.lower():
                return dept
        # Return cleaned as-is so OneHotEncoder handle_unknown='ignore' can process gracefully
        return cleaned

class PredictionResponse(BaseModel):
    prediction: int = Field(..., description="0 for Stays, 1 for Leaves")
    prediction_label: str = Field(..., description="'Stays' or 'Leaves'")
    attrition_probability: float = Field(..., description="Estimated probability of leaving (0.0 to 1.0)")
    attrition_percentage: str = Field(..., description="Formatted probability percentage")
    risk_level: str = Field(..., description="'Low', 'Medium', or 'High'")
    input_summary: Dict[str, Any] = Field(..., description="Summary of input features")
    disclaimer: str = Field(
        default="This prediction is a probabilistic estimate generated by a machine learning model. It should be used as a decision-support aid and never as the sole basis for employment decisions.",
        description="Model disclaimer"
    )

class HealthResponse(BaseModel):
    status: str
    service: str
    model_loaded: bool
    version: str
